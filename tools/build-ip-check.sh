#!/usr/bin/env bash
# Builds supabase/functions/ip-check/index.ts = shared logic (assets/js/ipcheck-core.js) + server.ts
# Run from the repository root after editing either file, then redeploy the function.
set -euo pipefail
out=supabase/functions/ip-check/index.ts
{
  echo '// GENERATED by tools/build-ip-check.sh: edit assets/js/ipcheck-core.js or server.ts, not this file.'
  echo '// @ts-nocheck'; echo '// deno-lint-ignore-file no-explicit-any'
  echo '// ===== shared logic (from assets/js/ipcheck-core.js) ====='
  sed -E 's/^export (function|const) /\1 /' assets/js/ipcheck-core.js
  echo
  cat supabase/functions/ip-check/server.ts
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
