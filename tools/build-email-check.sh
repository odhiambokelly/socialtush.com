#!/usr/bin/env bash
# Builds supabase/functions/email-check/index.ts = assets/js/email-core.js + server.ts. Run from the repo root, then redeploy.
set -euo pipefail
out=supabase/functions/email-check/index.ts
{
  echo '// GENERATED by tools/build-email-check.sh: edit assets/js/email-core.js or server.ts, not this file.'
  echo '// @ts-nocheck'
  sed -E 's/^export (async function|function|const) /\1 /' assets/js/email-core.js
  echo
  cat supabase/functions/email-check/server.ts
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
